package com.salyvn.packmerge.merge

import com.salyvn.packmerge.core.JsonIo
import com.salyvn.packmerge.core.PackFormat
import com.salyvn.packmerge.core.PackFormats
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.jsonObject

/** What one pack's `pack.mcmeta` claims about the versions it works on. */
data class DeclaredRange(val pack: String, val min: PackFormat?, val max: PackFormat?, val description: String?) {
    override fun toString(): String = "${min ?: "?"}..${max ?: "?"}"
}

/**
 * Reading and reconciling the version ranges of the packs being merged.
 *
 * A merged pack can only honestly claim the versions all of its inputs claim, so the range is the
 * intersection: the highest floor and the lowest ceiling. Packs generated by plugins tend to state a single
 * `pack_format` and nothing else, which reads as a one-format range and would drag the intersection down to
 * that one format — so a floor with no ceiling is treated as open-ended above, which is what the pack author
 * meant and what the client does with a missing `max_format` in the old era.
 */
object PackRanges {

    fun read(source: PackSource): DeclaredRange? {
        if ("pack.mcmeta" !in source.files) return null
        val pack = try {
            JsonIo.parse(source.readText("pack.mcmeta")).jsonObject["pack"] as? JsonObject
        } catch (failure: Exception) {
            null
        } ?: return DeclaredRange(source.name, null, null, null)

        val single = number(pack["pack_format"])
        val supported = pack["supported_formats"]
        val supportedMin = when (supported) {
            is JsonArray -> number(supported.firstOrNull())
            is JsonObject -> number(supported["min_inclusive"])
            is JsonPrimitive -> number(supported)
            else -> null
        }
        val supportedMax = when (supported) {
            is JsonArray -> number(supported.lastOrNull())
            is JsonObject -> number(supported["max_inclusive"])
            is JsonPrimitive -> number(supported)
            else -> null
        }
        val min = format(pack["min_format"]) ?: supportedMin?.let { PackFormat(it) } ?: single?.let { PackFormat(it) }
        val max = format(pack["max_format"]) ?: supportedMax?.let { PackFormat(it) }
        val description = (pack["description"] as? JsonPrimitive)?.takeIf { it.isString }?.content
        return DeclaredRange(source.name, min, max, description)
    }

    /**
     * The range the merged pack should claim: the highest floor and the lowest stated ceiling. Packs written
     * by plugins often state a floor and no ceiling at all, so when nobody states one the newest release the
     * tool knows is used and a note says so. When two packs cannot both be satisfied the caller is told, and
     * the last pack's own range is used, because its assets are the ones that win everywhere else.
     */
    fun reconcile(declared: List<DeclaredRange>, report: MergeReport): Pair<PackFormat, PackFormat>? {
        val withMin = declared.filter { it.min != null }
        if (withMin.isEmpty()) return null

        val floor = withMin.maxBy { it.min!!.major }
        val min = floor.min!!
        val ceiling = declared.filter { it.max != null }.minByOrNull { it.max!!.major }
        val newest = PackFormat(PackFormats.formatOf(PackFormats.newestRelease))
        val max = ceiling?.max ?: newest

        withMin.filter { it.min!!.major < min.major }.forEach { behind ->
            report.note(
                "pack.mcmeta",
                "${behind.pack} claims from format ${behind.min} but ${floor.pack} needs $min, so the merged pack starts at $min. " +
                    "${behind.pack} on its own still worked below that.",
            )
        }
        if (ceiling == null) {
            report.note("pack.mcmeta", "No pack states a maximum format, so the merged pack claims up to $newest (${PackFormats.newestRelease}). Pass --versions to say otherwise.")
        }
        if (max.major < min.major) {
            report.error(
                "pack.mcmeta",
                "The packs do not share a version: ${declared.joinToString(", ") { "${it.pack} $it" }}. " +
                    "The merged pack claims the last pack's own range; pass --versions to state one yourself.",
            )
            val last = declared.last()
            val fallbackMin = last.min ?: min
            return fallbackMin to (last.max ?: fallbackMin)
        }
        return min to max
    }

    private fun number(element: kotlinx.serialization.json.JsonElement?): Int? =
        (element as? JsonPrimitive)?.content?.toIntOrNull()

    /** `46` or `[97, 1]`, the two spellings the client accepts. */
    private fun format(element: kotlinx.serialization.json.JsonElement?): PackFormat? = when (element) {
        is JsonPrimitive -> element.content.toIntOrNull()?.let { PackFormat(it) }
        is JsonArray -> number(element.firstOrNull())?.let { PackFormat(it, number(element.getOrNull(1))) }
        else -> null
    }
}
